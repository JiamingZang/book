# ---------------------------------------------------------------- 图 4-7 斐波那契
def fig_p4_fib():
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5.9))

    # ---- 左：回撤画法 + confluence ----
    seq = [
        (0, 100, 103, 99, 102.5), (1, 102.5, 105, 101.5, 104.5),
        (2, 104.5, 107, 103.5, 106.5), (3, 106.5, 109, 105.5, 108.5),
        (4, 108.5, 111, 107.5, 110.5), (5, 110.5, 113, 109.5, 112.5),
        (6, 112.5, 115, 111.5, 114.5), (7, 114.5, 117, 113.5, 116.5),
        (8, 116.5, 119, 115.5, 118.5), (9, 118.5, 121, 117.5, 120.5),
        (10, 120.5, 120.5, 107.2, 107.8),  # 大回调到 61.8% 附近（HL）
        (11, 107.8, 112, 107.2, 111.5),    # 反弹
        (12, 111.5, 114.5, 110.5, 114),
        (13, 114, 116.5, 113, 116),
    ]
    for x, o, h, l, c in seq:
        candle(ax1, x, o, h, l, c, width=0.55)

    # 画法：起点(1,100.5) → 终点(10,120.5)
    ax1.annotate("", xy=(10, 120.5), xytext=(1, 100.5),
                 arrowprops=dict(arrowstyle="->", color=GRAY, lw=1.4, ls="--"), zorder=2)
    mark(ax1, 1, 100.5, "起点（近期低点）", dy=-3.2, color=GRAY, fs=9.5)
    mark(ax1, 10, 120.5, "终点（近期高点）", dy=1.8, color=GRAY, fs=9.5)

    # 回撤位 38.2% / 50% / 61.8%（从 100.5 到 120.5 → 高度 20）
    h0, h1 = 100.5, 120.5
    r38 = h1 - 0.382 * (h1 - h0)   # 112.86
    r50 = h1 - 0.50 * (h1 - h0)    # 110.50
    r62 = h1 - 0.618 * (h1 - h0)   # 108.14
    hl_line(ax1, 0.2, 14.5, r38, color=ORANGE, ls="--", lw=1.3, label="38.2%")
    hl_line(ax1, 0.2, 14.5, r50, color=GRAY, ls="--", lw=1.3, label="50%")
    hl_line(ax1, 0.2, 14.5, r62, color=TEAL, ls="--", lw=1.6, label="61.8%")
    # confluence 区：结构支撑区（107.2-110.5 阴影）重叠 61.8%
    ax1.add_patch(Rectangle((9.6, 107.2), 3.4, 3.3, facecolor=TEAL, alpha=0.12,
                            edgecolor=TEAL, ls="--", lw=1.0, zorder=1))
    annotate_mark(ax1, 10, 107.6, "HL 落 61.8% 附近\n+ 结构支撑区重叠\n= confluence 高质量入场区", 2.6, 112.5, color=TEAL, fs=10)
    mark(ax1, 11, 107.8, "入场", dy=-2.8, color=TEAL, fs=10)
    hl_line(ax1, 10.6, 12.6, 106.2, color=DOWN, ls=":", lw=1.6, label="止损")
    mark(ax1, 12.6, 106.2, "止损（HL 下方）", dy=-1.0, color=DOWN, fs=9.5)
    # 诚实评价
    mark(ax1, 7, 118.5, "有效性来自自我实现：\n太多人盯 61.8%，那里就有反应", dy=2.0, color=ORANGE, fs=9.5, box=True)
    style_ax(ax1, xlim=(-0.8, 15.6), ylim=(94, 127))

    # ---- 右：扩展目标 ----
    seq2 = [
        (0, 100, 103, 99, 102.5), (1, 102.5, 105, 101.5, 104.5),
        (2, 104.5, 107, 103.5, 106.5), (3, 106.5, 109, 105.5, 108.5),
        (4, 108.5, 111, 107.5, 110.5), (5, 110.5, 113, 109.5, 112.5),
        (6, 112.5, 115, 111.5, 114.5), (7, 114.5, 117, 113.5, 116.5),
        (8, 116.5, 119, 115.5, 118.5), (9, 118.5, 121, 117.5, 120.5),
        (10, 120.5, 120.5, 107.2, 107.8), (11, 107.8, 112, 107.2, 111.5),
        (12, 111.5, 115, 110.5, 114.5), (13, 114.5, 118.5, 113.5, 118),
        (14, 118, 122, 117, 121.5), (15, 121.5, 125.5, 121, 125),
        (16, 125, 129, 124.5, 128.5), (17, 128.5, 132.5, 128, 132),
        (18, 132, 134.5, 131.5, 134), (19, 134, 137, 133.5, 136.5),
        (20, 136.5, 139, 136, 138.5),
    ]
    for x, o, h, l, c in seq2:
        candle(ax2, x, o, h, l, c, width=0.55)

    # 扩展：从回撤低点 107.6 向上投影：127.2% / 161.8%（相对原波幅 20）
    L0, H0 = 100.5, 120.5
    base2 = 107.6
    e100 = base2 + (H0 - L0)          # 127.6
    e127 = base2 + 1.272 * (H0 - L0)  # 133.0
    e162 = base2 + 1.618 * (H0 - L0)  # 140.0
    hl_line(ax2, 0.2, 21.8, e100, color=GRAY, ls=":", lw=1.3, label="100% 等距")
    hl_line(ax2, 0.2, 21.8, e127, color=ORANGE, ls="--", lw=1.5, label="127.2% = TP1 候选")
    hl_line(ax2, 0.2, 21.8, e162, color=TEAL, ls="--", lw=1.6, label="161.8% = TP2 候选")
    mark(ax2, 10, 107.6, "回撤低点", dy=-3.0, color=GRAY, fs=9.5)
    annotate_mark(ax2, 15, 125.5, "从回撤低点向上投影\n（波幅 × 1.272 / 1.618）", 16.2, 113.5, color=DARK, fs=9.5)
    mark(ax2, 20, 138.5, "161.8% 到达", dy=1.8, color=TEAL, fs=10, box=True)
    mark(ax2, 18, 134, "127.2% 到达\n（近端结构位优先）", dy=1.6, color=ORANGE, fs=9.5, box=True)
    style_ax(ax2, xlim=(-0.8, 22.8), ylim=(94, 145))

    fig.suptitle("斐波那契回撤：HL + 61.8% 重叠 = confluence 入场区（左）；扩展位作止盈目标（右）",
                 fontsize=12.5, color=DARK, y=0.985)
    savefig(fig, "fig_p4_fib.png")


